def text(key: str, **values: object) -> str:
    """Return interface copy for the configured code-level language.

    Language selection is deliberately a code variable because the app has no
    user-facing settings use case yet. Keeping the catalog in the interface
    boundary preserves English as a parallel presentation detail without
    leaking localization decisions into Learn or Sandbox policy.

    @author Codex - added code-level interface language selection.
    """

    language = APP_LANGUAGE if APP_LANGUAGE in SUPPORTED_LANGUAGES else "en"
    template = _TEXT[language].get(key, _TEXT["en"].get(key, key))
    return template.format(**values)
